export const events: readonly NcaamSportEventSeed[] = Schedule.map(
  ([espnId, startsAt, homeTeam, awayTeam]) => {
    const id = `00000000-0000-4000-8000-000${espnId}`;

    return {
      id,
      _tag: "sports_game",
      sourceId: `sports_game:espn:${id}`,
      startsAt,
      availability: "active",
      details: {
        _tag: "sports_game",
        leagueId: "ncaam",
      },
      participants: [
        {
          _tag: "sports_game",
          details: {
            _tag: "sports_game",
            role: "home",
            title: homeTeam,
          },
        },
        {
          _tag: "sports_game",
          details: {
            _tag: "sports_game",
            role: "away",
            title: awayTeam,
          },
        },
      ],
    };
  },
);

export const getTeamFeedIds = (team: string) =>
  events
    .values()
    .filter((event) =>
      event.participants.some(
        (participant) => participant.details.title === team,
      ),
    )
    .map((event) => event.sourceId)
    .toArray();
